const at = "2026-11-05T00:00:00.000Z";

function strategy(id, title, thesis, hours, cost, claims, steps, firstAction, failureCondition) {
  return {
    id,
    title,
    thesis,
    steps,
    claims: claims.map(([cid, text, status]) => ({ id: cid, text, status, sourceIds: [] })),
    resources: "演示数据，不是模型输出。",
    firstAction,
    failureCondition,
    estimatedCost: cost,
    estimatedHours: hours,
  };
}

function build({ routes, disputes, revised, verdict }) {
  const strategies = routes.map((r) => strategy(...r));
  const claim = (id) => strategies.flatMap((s) => s.claims).find((c) => c.id === id);
  const attacks = disputes.map((d, i) => ({
    id: `atk-${i + 1}`,
    from: d.from,
    targetStrategyId: d.claim[0],
    targetClaimId: d.claim,
    claimQuote: claim(d.claim).text,
    reason: d.reason,
    impact: d.impact,
    verification: d.check,
    requests: d.expression
      ? [{ tool: "calculate", expression: d.expression, assumptions: d.assumptions ?? "" }]
      : [{ tool: "search_materials", query: d.query ?? d.title }],
    status: d.status,
  }));
  const evidence = disputes.map((d, i) => ({
    id: `ev-${i + 1}`,
    attackId: `atk-${i + 1}`,
    tool: d.expression ? "calculate" : "search_materials",
    status: d.expression ? "calculated" : d.found ? "found" : "unavailable",
    title: d.title,
    content: d.found ?? "",
    source: d.expression ? "计算工具" : "用户材料",
    sourceIds: [],
    expression: d.expression ?? null,
    result: d.result ?? null,
    assumptions: d.assumptions ?? "",
    createdAt: at,
  }));
  const revisions = routes.map((r, index) => {
    const id = r[0];
    const base = strategies[index];
    const change = revised[id];
    const answers = disputes.flatMap((d, i) =>
      d.claim[0] === id
        ? [
            {
              attackId: `atk-${i + 1}`,
              decision: d.answer,
              reason: d.reply,
              evidenceIds: [`ev-${i + 1}`],
              change: d.change ?? "",
            },
          ]
        : [],
    );
    return {
      strategyId: id,
      strategy: {
        ...base,
        ...(change.thesis ? { thesis: change.thesis } : {}),
        ...(change.hours ? { estimatedHours: change.hours } : {}),
        ...(change.steps ? { steps: change.steps } : {}),
        ...(change.first ? { firstAction: change.first } : {}),
        claims: change.claims
          ? change.claims.map(([cid, text, status]) => ({ id: cid, text, status, sourceIds: [] }))
          : base.claims,
      },
      responses: answers,
      summary: change.summary,
      changed: !!(change.thesis || change.hours || change.steps || change.first || change.claims),
    };
  });
  return {
    strategies,
    attacks,
    evidence,
    revisions,
    verdict: {
      evidenceIds: evidence.map((e) => e.id),
      attackFindings: disputes
        .map((d, i) => ({
          attackId: `atk-${i + 1}`,
          status: d.status,
          reason: d.reply,
          evidenceIds: [`ev-${i + 1}`],
        }))
        .filter((f) => f.status !== "pending"),
      ...verdict,
    },
  };
}

